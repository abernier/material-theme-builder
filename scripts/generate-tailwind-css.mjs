// Generates `src/tailwind.css` from `toTailwind()`, and mirrors it into
// `dist/` for publishing.
//
// The stylesheet used to be maintained by hand alongside `toTailwind()`, which
// is how `--color-surface-tint` and `--color-surface-variant` came to be
// missing from one and not the other. Generating it from the exporter removes
// the possibility: there is one mapping now, and the file is its output.
//
//   node scripts/generate-tailwind-css.mjs
//
// Both copies are build output and both are gitignored: `dist/` is what ships,
// `src/` is what Storybook `@import`s, so that its stylesheet can dogfood the
// same stylesheet-plus-plugin pairing the README recommends rather than a
// second-best arrangement of its own. That is why `pnpm run storybook` builds
// first.
//
// Runs from `tsup`'s `onSuccess`, so `pnpm run build` keeps both current.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import prettier from "prettier";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Header explaining to a reader of `dist/tailwind.css` why editing is futile. */
export const BANNER = `/*
 * Generated by \`scripts/generate-tailwind-css.mjs\` -- do not edit.
 *
 * Custom colors are not in here: they depend on your config, so they come from
 * the plugin instead.
 *
 *   @plugin "material-theme-builder/tailwind" {
 *     custom-colors: myCustomColor1, myCustomColor2;
 *   }
 */
`;

/**
 * Wrap a `toTailwind()` block into the file as shipped.
 *
 * @param {string} themeCss the `@theme inline { ... }` block
 * @returns {Promise<string>}
 */
export async function formatTailwindCss(themeCss) {
  const options = await prettier.resolveConfig(join(root, "src/tailwind.css"));

  return prettier.format(BANNER + themeCss, { ...options, parser: "css" });
}

// The output names variables, never colors, so the source is arbitrary --
// `toTailwind()` returns the same string whatever it is asked about.
const SOURCE = "#6750A4";

/**
 * The file's contents, from whichever `builder` the caller can reach.
 *
 * Taking it as an argument is what lets Storybook regenerate on the fly: it
 * loads `builder` from source through Vite, where this module can only reach
 * the built bundle.
 *
 * @param {(source: string) => { toTailwind: () => string }} builder
 * @returns {Promise<string>}
 */
export const tailwindCssFrom = (builder) =>
  formatTailwindCss(builder(SOURCE).toTailwind());

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  // Imported lazily, and through a URL rather than a literal specifier, so
  // that only the writing half needs a build to have happened -- a literal
  // would have Vite resolve `dist/` at transform time when the test imports
  // this module.
  const { builder } = await import(
    new URL("../dist/index.js", import.meta.url).href
  );
  const css = await tailwindCssFrom(builder);

  for (const target of ["src/tailwind.css", "dist/tailwind.css"]) {
    const path = join(root, target);
    mkdirSync(dirname(path), { recursive: true });

    // Only write on a real change, so a build leaves the working tree alone
    // when there is nothing to say.
    if (existsSync(path) && readFileSync(path, "utf8") === css) continue;

    writeFileSync(path, css);
    console.log(`wrote ${target}`);
  }
}
