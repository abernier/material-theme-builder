function hex(argb: number) {
  return hexFromArgb(argb).toUpperCase();
}

// The `--md-ref-palette-<name>-<tone>` values of toCss()'s `:root` rule, in
// the shape of toJson().palettes.
function refPalettesFromCss(css: string) {
  const root = css.slice(css.indexOf(":root {"), css.indexOf(".dark {"));
  const palettes: Record<string, Record<string, string>> = {};

  const refPaletteVar = /--md-ref-palette-([a-z0-9-]+)-(\d+):(#[0-9a-f]{6});/g;
  for (const [, name, tone, value] of root.matchAll(refPaletteVar)) {
    if (!name || !tone || !value) continue;
    palettes[name] ??= {};
    palettes[name][tone] = value.toUpperCase();
  }

  return palettes;
}

// The DynamicScheme builder() renders, rebuilt from the palettes it exposes.
function renderedScheme(
  { source, options = {} }: Input,
  allPalettes: Record<string, TonalPalette>,
  isDark: boolean,
) {
  const palette = (name: string) => {
    const found = allPalettes[name];
    if (!found) throw new Error(`No '${name}' palette`);
    return found;
  };

  const scheme = new DynamicScheme({
    sourceColorArgb: argbFromHex(options.primary ?? source),
    variant: schemeToVariant[options.scheme ?? "tonalSpot"],
    contrastLevel: options.contrast ?? 0,
    isDark,
    primaryPalette: palette("primary"),
    secondaryPalette: palette("secondary"),
    tertiaryPalette: palette("tertiary"),
    neutralPalette: palette("neutral"),
    neutralVariantPalette: palette("neutral-variant"),
  });
  scheme.errorPalette = palette("error");

  return scheme;
}

describe("builder › toJson().palettes", () => {
  for (const input of inputs) {
    it(`should equal the --md-ref-palette-* of toCss() (${input.label})`, () => {
      const theme = builder(input.source, input.options);
      const { palettes } = theme.toJson();

      expect(palettes).toEqual(refPalettesFromCss(theme.toCss()));
      expect(palettes).toHaveProperty("error");
      for (const tones of Object.values(palettes)) {
        expect(Object.keys(tones).map(Number)).toEqual([...STANDARD_TONES]);
      }
    });
  }

  for (const input of inputs) {
    it(`should hold the palette every system role is a tone of (${input.label})`, () => {
      const theme = builder(input.source, input.options);
      const { palettes } = theme.toJson();

      for (const isDark of [false, true]) {
        const scheme = renderedScheme(input, theme.allPalettes, isDark);
        const rendered = isDark
          ? theme.mergedColorsDark
          : theme.mergedColorsLight;

        for (const tokenName of tokenNames) {
          const role = MaterialDynamicColors[tokenName];
          const roleHex = hex(role.getArgb(scheme));

          // The scheme rebuilt here is the one builder() rendered
          expect(roleHex, tokenName).toBe(hex(rendered[tokenName] ?? 0));

          // The role is a tone of its palette -- at whatever tone contrast
          // and fidelity landed it on, not necessarily an exported one
          const palette = role.palette(scheme);
          expect(roleHex, tokenName).toBe(
            hex(palette.tone(role.getTone(scheme))),
          );

          // ...and that palette is the one exported under its key
          const [name] =
            Object.entries(theme.allPalettes).find(
              ([, exported]) => exported === palette,
            ) ?? [];
          expect(name, tokenName).toBeDefined();
          expect(palettes[kebabCase(name)], tokenName).toEqual(
            Object.fromEntries(
              STANDARD_TONES.map((tone) => [
                tone.toString(),
                hex(palette.tone(tone)),
              ]),
            ),
          );
        }
      }
    });
  }
});
